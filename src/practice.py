# 1. ЧТО ТАКОЕ IMPORT?
# Python сам по себе лёгкий, в нём нет встроенных инструментов для БД и таблиц.
# Библиотеки (sqlite3, pandas) — это наборы готовых инструментов других разработчиков.
# Команда "import" достаёт нужный чемодан с инструментами с диска.
import sqlite3          # Достали чемодан для работы с файлами SQLite
import pandas as pd     # Достали чемодан для таблиц. "as pd" — это короткая кличка (псевдоним),
                        # чтобы каждый раз не писать длинное слово pandas.

# ---------------------------------------------------------------------
# 2. ЧТО ДЕЛАЕТ ТОЧКА (.)?
# Точка означает: "У КОГО ВЗЯТЬ" . "ЧТО СДЕЛАТЬ" (или ЧТО ВЗЯТЬ).
# Пример из жизни: собака.лаять() или машина.завести()
# sqlite3.connect(...) — значит: "Эй, чемодан sqlite3, запусти СВОЮ команду connect".

# 3. ЧТО ТАКОЕ CONNECT И КАВЫЧКИ?
# База "fintech_sandbox.db" — это просто закрытый файл на твоём жестком диске.
# connect() протягивает провод от Python прямо внутрь этого файла.
# Результат (этот провод) мы кладём в переменную conn (сокращение от connection).
# 
# ЗАЧЕМ КАВЫЧКИ "" или ''?
# Без кавычек Python подумает, что data — это имя переменной или команда.
# Кавычки говорят: "Это просто ТЕКСТ (буквы пути к файлу), не пытайся его исполнять!".
# Разницы между '' и "" НЕТ. Они делают абсолютно одно и то же.
conn = sqlite3.connect("data/fintech_sandbox.db")

# ---------------------------------------------------------------------
# 4. ВЫГРУЗКА ДАННЫХ В ТАБЛИЦУ (DATAFRAME)
# pd.read_sql("запрос", провод)
# Инструмент pd берёт провод conn, выполняет внутри базы SQL-запрос,
# забирает строки и строит в памяти красивую двухмерную таблицу DataFrame.
# Мы сохраняем её в коробку df_users.
df_users = pd.read_sql("SELECT * FROM users", conn)

# ---------------------------------------------------------------------
# 5. КРУГЛЫЕ () VS КВАДРАТНЫЕ [] СКОБКИ — ГЛАВНОЕ ПРАВИЛО:
#
# ( ) КРУГЛЫЕ — ЭТО ДЕЙСТВИЕ (ГЛАГОЛ / ФУНКЦИЯ):
#     Ставятся, когда ты заставляешь компьютер что-то сделать.
#     print()       -> "напечатай!"
#     connect()     -> "подключись!"
#     groupby()     -> "сгруппируй!"
#     nunique()     -> "посчитай уникальные!"
#
# [ ] КВАДРАТНЫЕ — ЭТО ВЫБОР ДЕТАЛИ / СТОЛБЦА (КАРМАН / ИНДЕКС):
#     Они ничего не запускают. Они просто лезут внутрь коробки и берут конкретную колонку.
#     df_users['user_id'] -> "из таблицы возьми только столбец с именем user_id".
#
# ЦЕПОЧКА В СБОРЕ:
# df_users .groupby('status') ['user_id'] .nunique()
# [Таблица] .[Сгруппируй по статусу] [Возьми столбец ID] .[Посчитай уникальные]
# =====================================================================

print(df_users.groupby('status')['user_id'].nunique())